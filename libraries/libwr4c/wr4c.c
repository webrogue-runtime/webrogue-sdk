static wr4c_window_t* s_all_windows = NULL;
static size_t s_all_windows_count = 0;

void wr4c_make_window(wr4c_window_t *out_window) {
    wr4c_window_t window = malloc(sizeof(wr4c_window_s));
    s_all_windows_count++;
    if(s_all_windows_count == 1) {
        s_all_windows = malloc(sizeof(wr4c_window_t));
    } else {
        s_all_windows = realloc(s_all_windows, s_all_windows_count * sizeof(wr4c_window_t));
    }
    size_t internal_id = s_all_windows_count - 1;
    s_all_windows[internal_id] = NULL;
    window->handle = webrogue_gfx_windowing_make_window();
    // TODO find NULL holes in s_all_windows and reuse them
    window->internal_id = internal_id;
    s_all_windows[window->internal_id] = window;

    webrogue_gfx_windowing_borrow_window_t borrow = webrogue_gfx_windowing_borrow_window(window->handle);
    window->window_event_stream = webrogue_gfx_windowing_method_window_event_stream(borrow);
    window->read_in_flight = false;

    *out_window = window;
}

void wr4c_destroy_window(wr4c_window_t window) {
    if (window->read_in_flight) {
        webrogue_gfx_windowing_stream_window_event_cancel_read(window->window_event_stream);
    }
    webrogue_gfx_windowing_stream_window_event_drop_readable(window->window_event_stream);
    webrogue_gfx_windowing_close_window(window->handle);
    s_all_windows[window->internal_id] = NULL;
    free(window);
}


void wr4c_logical_size(wr4c_window_t window, int *width, int *height) {
    gfx_tuple2_u32_u32_t ret;
    webrogue_gfx_windowing_borrow_window_t borrow = webrogue_gfx_windowing_borrow_window(window->handle);
    webrogue_gfx_windowing_method_window_get_logical_size(borrow, &ret);
    //   webrogue_gfx_windowing_window_drop_borrow(borrow);
    *width = ret.f0;
    *height = ret.f1;
}

