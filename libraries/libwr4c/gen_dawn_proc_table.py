#!/usr/bin/env python3
"""Generate a minimal Dawn-compatible proc table shim.

ANGLE's WebGPU backend talks to the WebGPU implementation through a
``DawnProcTable``: a struct of function pointers whose members are named like
the ``wgpu*`` C entry points with the ``wgpu`` prefix dropped.  On Webrogue the
implementation is the ``wasi:webgpu`` C API provided by libwr4c, so this script
emits:

  * ``include/dawn/dawn_proc_table.h`` - the struct definition,
  * ``include/dawn/dawn_proc.h`` - the header ANGLE includes,
  * ``webgpu_proc_table.c`` - a table filled with the libwr4c entry points.

Only the members ANGLE actually references are emitted.  Every emitted member
must have a strong definition in libwr4c, otherwise linking fails loudly
instead of silently dispatching through a stub.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEBGPU_H = os.path.join(HERE, "..", "wasi-webgpu-headers", "webgpu", "webgpu.h")

# Members ANGLE's src/libANGLE/renderer/wgpu backend calls through the table.
MEMBERS = """
adapterAddRef
adapterGetInstance
adapterRequestDevice
bufferGetConstMappedRange
bufferGetMappedRange
bufferGetMapState
bufferGetSize
bufferGetUsage
bufferMapAsync
bufferUnmap
commandEncoderBeginRenderPass
commandEncoderCopyBufferToBuffer
commandEncoderCopyBufferToTexture
commandEncoderCopyTextureToBuffer
commandEncoderCopyTextureToTexture
commandEncoderFinish
createInstance
deviceAddRef
deviceCreateBindGroup
deviceCreateBindGroupLayout
deviceCreateBuffer
deviceCreateCommandEncoder
deviceCreatePipelineLayout
deviceCreateRenderPipeline
deviceCreateSampler
deviceCreateShaderModule
deviceCreateTexture
deviceGetAdapter
deviceGetLimits
deviceGetQueue
devicePopErrorScope
devicePushErrorScope
instanceAddRef
instanceCreateSurface
instanceRequestAdapter
instanceWaitAny
queueOnSubmittedWorkDone
queueSubmit
queueWriteBuffer
renderPassEncoderDraw
renderPassEncoderDrawIndexed
renderPassEncoderEnd
renderPassEncoderSetBindGroup
renderPassEncoderSetBlendConstant
renderPassEncoderSetIndexBuffer
renderPassEncoderSetPipeline
renderPassEncoderSetScissorRect
renderPassEncoderSetStencilReference
renderPassEncoderSetVertexBuffer
renderPassEncoderSetViewport
shaderModuleGetCompilationInfo
surfaceConfigure
surfaceGetCapabilities
surfaceGetCurrentTexture
surfacePresent
textureAddRef
textureCreateView
textureGetDepthOrArrayLayers
textureGetDimension
textureGetFormat
textureGetHeight
textureGetMipLevelCount
textureGetSampleCount
textureGetUsage
textureGetWidth
""".split()

# ANGLE wraps every WGPU object handle in a ref-counted WrapperBase, which calls
# <object>AddRef / <object>Release through the table.
OBJECTS = """
adapter
bindGroup
bindGroupLayout
buffer
commandBuffer
commandEncoder
computePassEncoder
computePipeline
device
externalTexture
instance
pipelineLayout
querySet
queue
renderBundle
renderBundleEncoder
renderPassEncoder
renderPipeline
sampler
shaderModule
surface
texture
textureView
""".split()


def load_proc_types():
    with open(WEBGPU_H, encoding="utf-8") as f:
        text = f.read()
    types = {}
    for match in re.finditer(r"typedef\s+[^;]*?\(\s*\*\s*(WGPUProc\w+)\s*\)\s*\(", text):
        name = match.group(1)
        suffix = name[len("WGPUProc"):]
        member = suffix[0].lower() + suffix[1:]
        types[member] = name
    return types


# Members that have no WGPUProc typedef in webgpu.h: either Dawn extensions or
# ref-counting entry points for Dawn-only handle types.
SYNTHETIC = {
    "adapterGetInstance": ("WGPUInstance", "WGPUAdapter"),
    "deviceGetAdapter": ("WGPUAdapter", "WGPUDevice"),
}


def synthetic_type(member):
    ret, args = SYNTHETIC[member]
    return f"{ret} (*)({args})"


def synthetic_decl(member):
    ret, args = SYNTHETIC[member]
    return f"{ret} {c_function(member)}({args});"


def c_function(member):
    return "wgpu" + member[0].upper() + member[1:]


def main():
    proc_types = load_proc_types()

    members = list(MEMBERS)
    for obj in OBJECTS:
        members.append(obj + "AddRef")
        members.append(obj + "Release")

    seen = set()
    ordered = []
    for member in members:
        if member in seen:
            continue
        seen.add(member)
        if member not in proc_types and member not in SYNTHETIC:
            sys.exit(f"unknown proc table member: {member}")
        ordered.append(member)

    out_dir = os.path.join(HERE, "include", "dawn")
    os.makedirs(out_dir, exist_ok=True)

    with open(os.path.join(out_dir, "dawn_proc_table.h"), "w", encoding="utf-8") as f:
        f.write("// Generated by gen_dawn_proc_table.py. DO NOT EDIT.\n")
        f.write("//\n")
        f.write("// Minimal DawnProcTable for the Webrogue WebGPU backend. It only\n")
        f.write("// declares the members ANGLE uses; the entry points come from the\n")
        f.write("// wasi:webgpu C API implemented by libwr4c.\n")
        f.write("#ifndef DAWN_DAWN_PROC_TABLE_H_\n")
        f.write("#define DAWN_DAWN_PROC_TABLE_H_\n\n")
        f.write("#include <webgpu/webgpu.h>\n\n")
        f.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        f.write("typedef struct DawnProcTable {\n")
        for member in ordered:
            if member in proc_types:
                f.write(f"    {proc_types[member]} {member};\n")
            else:
                ret, args = SYNTHETIC[member]
                f.write(f"    {ret} (*{member})({args});\n")
        f.write("} DawnProcTable;\n\n")
        f.write("#ifdef __cplusplus\n}\n#endif\n\n")
        f.write("#endif  // DAWN_DAWN_PROC_TABLE_H_\n")

    with open(os.path.join(out_dir, "dawn_proc.h"), "w", encoding="utf-8") as f:
        f.write("// Generated by gen_dawn_proc_table.py. DO NOT EDIT.\n")
        f.write("#ifndef DAWN_DAWN_PROC_H_\n")
        f.write("#define DAWN_DAWN_PROC_H_\n\n")
        f.write("#include \"dawn/dawn_proc_table.h\"\n\n")
        f.write("#endif  // DAWN_DAWN_PROC_H_\n")

    with open(os.path.join(HERE, "webgpu_proc_table.c"), "w", encoding="utf-8") as f:
        f.write("// Generated by gen_dawn_proc_table.py. DO NOT EDIT.\n")
        f.write("//\n")
        f.write("// The DawnProcTable ANGLE's WebGPU backend dispatches through. It is\n")
        f.write("// filled with the libwr4c implementation of the standard WebGPU C API.\n\n")
        f.write("#include <webgpu/webgpu.h>\n\n")
        f.write("#include \"dawn/dawn_proc_table.h\"\n")
        f.write("#include \"wr4c_webgpu.h\"\n\n")
        for member in ordered:
            if member not in proc_types:
                f.write(f"extern {synthetic_decl(member)}\n")
        f.write("\nstatic const DawnProcTable wr4cDawnProcTable = {\n")
        for member in ordered:
            f.write(f"    .{member} = {c_function(member)},\n")
        f.write("};\n\n")
        f.write("const DawnProcTable *wr4c_get_dawn_proc_table(void) {\n")
        f.write("    return &wr4cDawnProcTable;\n")
        f.write("}\n")

    print(f"generated {len(ordered)} proc table members")


if __name__ == "__main__":
    main()
